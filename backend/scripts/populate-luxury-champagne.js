async function populateLuxuryChampagne() {
  console.log('🥂 Starting luxury champagne and sparkling wine population...')
  
  try {
    let createdCount = 0
    
    for (const champagneData of luxuryChampagnes) {
      const { specifications, images, variants, awards, ...champagneInfo } = champagneData
      
      // Generate unique SKU if not provided
      if (!champagneInfo.sku) {
        champagneInfo.sku = `CHAMP-${Date.now()}-${Math.random().toString(36).substr(2, 9)}`
      }
      
      // Create champagne with all related data
      const champagne = await prisma.wine.create({
        data: {
          ...champagneInfo,
          // Create wine specification if provided
          ...(specifications && {
            specification: {
              create: {
                grapeVariety: JSON.stringify(specifications.grapeVariety),
                alcoholContent: specifications.alcoholContent || champagneInfo.alcoholContent,
                servingTemp: specifications.servingTemp,
                tastingNotes: champagneInfo.tastingNotes,
                foodPairing: specifications.foodPairing,
                awards: JSON.stringify(specifications.awards || []),
                ph: specifications.ph,
                residualSugar: specifications.residualSugar,
                tannins: specifications.tannins,
                acidity: specifications.acidity,
                body: specifications.body,
                finish: specifications.finish,
                oakTreatment: specifications.oakTreatment,
                malolacticFermentation: specifications.malolacticFermentation
              }
            }
          }),
          // Create wine inventory
          inventory: {
            create: {
              quantity: champagneInfo.stock || 0,
              availableQty: champagneInfo.stock || 0,
              location: 'luxury_champagne_cellar',
              lowStockThreshold: 3,
              reorderPoint: 1,
              temperature: 12.0,
              humidity: 75.0
            }
          },
          // Create wine pricing
          prices: {
            create: {
              currency: champagneInfo.currency || 'EUR',
              originalPrice: champagneInfo.originalPrice,
              currentPrice: champagneInfo.currentPrice,
              discountType: 'PERCENTAGE',
              discountValue: champagneInfo.discountPercent,
              tier: 'LUXURY',
              isActive: true,
              isPromotion: true,
              promotionCode: 'LUXURY80'
            }
          }
        }
      })
      
      createdCount++
      console.log(`✅ Created luxury champagne ${createdCount}: ${champagne.name}`)
    }
    
    console.log(`🎉 Successfully created ${createdCount} luxury champagnes!`)
    
  } catch (error) {
    console.error('❌ Error populating luxury champagnes:', error)
    throw error
  }
}

// Run the population script
populateLuxuryChampagne()
  .catch((e) => {
    console.error('❌ Script failed:', e)
    process.exit(1)
  })
  .finally(async () => {
    await prisma.$disconnect()
  })
